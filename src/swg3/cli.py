"""Command line: `swg3 <group> <command>`.

Groups (the RNG lives on the site, `web/`):
  pk3     show and validate pk3 files
  recipe  check recipes generated by the site (docs/project/recipe.md)
  keys    minimal LDN key file in .secrets/ (docs/project/keys.md)
"""

import argparse
import sys
from pathlib import Path

from . import keys, recipe
from .gen3 import pk3, species, validate


def _parse_ivs(text: str | None) -> dict | None:
    if text is None:
        return None
    values = [int(v) for v in text.split("/")]
    if len(values) != 6 or not all(0 <= v <= 31 for v in values):
        raise SystemExit(f"IVs {text!r}: use 6 values from 0 to 31, e.g. 31/31/31/31/31/31")
    return dict(zip(pk3.STATS, values))


def cmd_pk3_show(args) -> int:
    mon, _ = pk3.load(Path(args.file).read_bytes())
    names = validate.species_names()
    print(f"species   {mon.species} {names.get(mon.species, '?')}")
    print(f"nickname  {mon.nickname}")
    print(f"OT        {mon.ot_name}  TID {mon.tid}  SID {mon.sid}")
    print(f"PID       {mon.personality:08X}  {mon.nature}{'  shiny' if mon.is_shiny else ''}")
    print(f"IVs       {'/'.join(str(mon.ivs[k]) for k in pk3.STATS)}")
    print(f"EVs       {'/'.join(str(mon.evs[k]) for k in pk3.STATS)}")
    print(f"moves     {', '.join(str(m) for m in mon.moves)}")
    print(f"item      {mon.held_item}  ball {mon.ball}  met level {mon.met_level}")
    if validate.valid_species(mon.species):
        level = species.mon_level(mon)
        stats = species.mon_stats(mon, level)
        print(f"level     {level} (from experience {mon.experience})")
        print(f"stats     {'/'.join(str(stats[k]) for k in pk3.STATS)} (calculated)")
        print(f"moves     {', '.join(species.move_name(m) for m in mon.moves if m)}")
    if mon.is_party:
        print(f"party level {mon.level}")
    return 0


def cmd_pk3_check(args) -> int:
    worst = 0
    for name in args.files:
        mon, _ = pk3.load(Path(name).read_bytes())
        issues = validate.check(mon)
        if not issues:
            print(f"{name}: ok")
        for issue in issues:
            print(f"{name}: {issue.level}: {issue.field}: {issue.message}")
            if issue.level == "error":
                worst = 1
    return worst


def cmd_recipe_check(args) -> int:
    data, mon = recipe.load(Path(args.file).read_text(encoding="utf-8"))
    game = data["game"]
    print(f"action    {data['action']} ({game['title']}, {game['language']}, revision {game['revision']})")
    print(f"offer     {species.info(mon.species)['name']} {mon.nickname!r} PID {mon.personality:08X} "
          f"level {species.mon_level(mon)}")
    if data["offer"].get("evolves_to"):
        print(f"evolves   {data['offer']['evolves_to']}")
    print(f"received  {(data.get('receive') or {}).get('save_as') or 'do not save'}")
    for number, step in enumerate(data["steps"], 1):
        print(f"{number:>2}. [{step['who']}] {step['text']}")
    return 0


def cmd_keys_minimize(args) -> int:
    source = Path(args.source).expanduser() if args.source else None
    target = Path(args.target).expanduser() if args.target else None
    path = keys.minimize(source, target)
    print(f"minimal file written to {path} (mode 600; the original was not changed)")
    ignored = keys.git_ignored(path)
    if ignored is False:
        print("WARNING: git does not ignore this path", file=sys.stderr)
        return 1
    return 0


def cmd_keys_check(args) -> int:
    info = keys.status(Path(args.path).expanduser() if args.path else None)
    print(f"file      {info['path']}")
    if not info["exists"]:
        print("status    missing; run `swg3 keys minimize`")
        return 1
    print(f"mode      {info['mode']}{'' if info['mode'] == '600' else '  (use chmod 600)'}")
    ignored = {True: "yes", False: "NO", None: "outside a git repository"}[info["ignored"]]
    print(f"ignored   {ignored}")
    if "error" in info:
        print(f"error     {info['error']}")
        return 1
    for name, present in info["keys"].items():
        print(f"{'ok' if present else 'missing':<9} {name}")
    if info["extra"]:
        print(f"extra     {len(info['extra'])} entry(ies) besides the LDN ones; regenerate with `swg3 keys minimize`")
    bad = not all(info["keys"].values()) or info["mode"] != "600" or info["ignored"] is False
    return 1 if bad else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="swg3", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    groups = parser.add_subparsers(dest="group", required=True)

    pk3_parser = groups.add_parser("pk3", help="pk3 files")
    pk3_cmds = pk3_parser.add_subparsers(dest="command", required=True)
    show = pk3_cmds.add_parser("show", help="show fields")
    show.add_argument("file")
    show.set_defaults(func=cmd_pk3_show)
    check = pk3_cmds.add_parser("check", help="validate (exit code 1 on error)")
    check.add_argument("files", nargs="+")
    check.set_defaults(func=cmd_pk3_check)

    recipe_parser = groups.add_parser("recipe", help="recipes for the trade host")
    recipe_cmds = recipe_parser.add_subparsers(dest="command", required=True)
    recipe_check = recipe_cmds.add_parser("check", help="check and summarize a recipe")
    recipe_check.add_argument("file")
    recipe_check.set_defaults(func=cmd_recipe_check)

    keys_parser = groups.add_parser("keys", help="console keys for LDN")
    keys_cmds = keys_parser.add_subparsers(dest="command", required=True)
    minimize = keys_cmds.add_parser("minimize", help="write .secrets/ldn.keys with only the LDN keys")
    minimize.add_argument("--from", dest="source", help=f"source prod.keys (default {keys.DEFAULT_SOURCE})")
    minimize.add_argument("--to", dest="target", help="target (default .secrets/ldn.keys)")
    minimize.set_defaults(func=cmd_keys_minimize)
    keys_check = keys_cmds.add_parser("check", help="check the minimal file without showing values")
    keys_check.add_argument("path", nargs="?")
    keys_check.set_defaults(func=cmd_keys_check)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if getattr(args, "shiny", False) and (args.tid is None or args.sid is None):
        raise SystemExit("--shiny requires --tid and --sid")
    try:
        return args.func(args)
    except (KeyError, ValueError) as error:
        raise SystemExit(str(error).strip("'\""))


if __name__ == "__main__":
    sys.exit(main())
